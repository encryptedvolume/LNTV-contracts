import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.slice(2).includes('--check');
const read = path => readFileSync(resolve(root, path), 'utf8');
const sha = content => createHash('sha256').update(content).digest('hex');
const json = value => JSON.stringify(value, null, 2) + '\n';
const build = spawnSync(process.execPath, ['scripts/foundry.mjs', 'forge', 'build'], {
  cwd: root, stdio: 'inherit',
});
if (build.status !== 0) process.exit(build.status ?? 1);

const names = ['RankedAuction', 'AuctionEdition', 'RoyaltyMarketplace'];
const version = JSON.parse(read('package.json')).version;
const deployments = JSON.parse(read('deployments/networks.json'));
for (const [chain, deployment] of Object.entries(deployments)) {
  if (!/^\d+$/.test(chain) || !Number.isSafeInteger(deployment.chainId) || deployment.chainId <= 0 || String(deployment.chainId) !== chain) {
    throw new Error(`Invalid chain ID: ${chain}`);
  }
  for (const field of ['auction', 'edition', 'marketplace']) {
    if (!/^0x[0-9a-fA-F]{40}$/.test(deployment[field]) || /^0x0{40}$/i.test(deployment[field])) {
      throw new Error(`Invalid ${field} address on chain ${chain}`);
    }
  }
}
const abis = Object.fromEntries(names.map(name => [name, JSON.parse(read(`out/${name}.sol/${name}.json`)).abi]));
const sourceSha256 = Object.fromEntries([...names, 'TokenRescue'].map(name => [`src/${name}.sol`, sha(read(`src/${name}.sol`))]));
const banner = '// Generated by npm run interface:export. Do not edit.\n';
const files = {
  'index.js': banner + `export const version = ${JSON.stringify(version)};\n` +
    names.map(name => `export const ${name}Abi = ${JSON.stringify(abis[name])};\n`).join('') +
    `export const deployments = ${JSON.stringify(deployments)};\n`,
  'index.d.ts': banner + `export declare const version: ${JSON.stringify(version)};\n` +
    names.map(name => `export declare const ${name}Abi: ${JSON.stringify(abis[name])};\n`).join('') +
    'export declare const deployments: Readonly<Record<string, { chainId: number; auction: `0x${string}`; edition: `0x${string}`; marketplace: `0x${string}` }>>;\n',
  'deployments.json': json(deployments),
  'package.json': json({ name: '@lntv/contracts-interface', version, private: true, type: 'module', main: './index.js', types: './index.d.ts' }),
};
files['manifest.json'] = json({
  schemaVersion: 1, version, repository: 'https://github.com/encryptedvolume/LNTV-contracts', sourceSha256,
  files: Object.fromEntries(Object.entries(files).map(([path, content]) => [path, sha(content)])),
});
mkdirSync(resolve(root, 'interface'), { recursive: true });
for (const [name, content] of Object.entries(files)) {
  if (check) {
    if (read(`interface/${name}`) !== content) throw new Error(`Stale interface/${name}; run npm run interface:export`);
  } else writeFileSync(resolve(root, 'interface', name), content);
}
console.log(`${check ? 'Verified' : 'Exported'} contract interface ${version}; ${Object.keys(deployments).length} deployed networks.`);
